-- D-126: 벨트별 "흔히 배우는 기술" 목록 — 화이트 44 · 블루 61 · 퍼플 48 · 브라운 28 · 블랙 17.
-- 공식 커리큘럼은 없고 체육관마다 달라서 "필수"가 아니라 "흔히"로 부른다. 운영자(본인) 판단으로 흔한 커리큘럼을 따라 골랐고 사람이 검증하지 않았다(D-86).
-- 브라운 · 블랙은 정해진 커리큘럼이 거의 없어 "이 시기에 많이 다듬는 것"으로 짧게. 유소년 벨트는 앱이 화이트 목록을 보여 준다.
-- 누구나 보기, 쓰기는 마이그레이션으로만(drills 와 같음). 없는 기술 slug 가 있으면 멈춘다.

create table if not exists public.belt_techniques (
  id uuid primary key default gen_random_uuid(),
  belt text not null check (belt in ('white','blue','purple','brown','black')),
  technique_slug text not null,
  sort_order int not null default 0,
  created_at timestamptz not null default now(),
  unique (belt, technique_slug)
);
alter table public.belt_techniques enable row level security;
create policy "belt_techniques: 누구나 보기" on public.belt_techniques for select using (true);


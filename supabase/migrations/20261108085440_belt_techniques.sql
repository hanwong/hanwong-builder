-- 없는 slug 가 있으면 멈춘다
do $$
declare bad text;
begin
  select string_agg(b.technique_slug, ', ') into bad
  from public.belt_techniques b
  left join public.techniques t on t.slug = b.technique_slug and t.owner_id is null
  where t.id is null;
  if bad is not null then
    raise exception 'belt_techniques: 없는 기술 slug — %', bad;
  end if;
end $$;
